app.Theme = Theme

-- Semantic surface roles. Each role names its fill, colour token and opacity
-- token; PaintSurface is the single place that turns a role into a backdrop.
-- "embedded" has no edge on purpose: grouping comes from a small value change,
-- not from a border around every row. "button" lost its edge too — an idle
-- control is a flat patch, and the accent hairline is a state the control draws
-- itself, which is what stops a settings page from reading as a grid of boxes.
local SURFACES = {
    window = { fill = "panel", color = "surface", edge = true, opacity = "windowOpacity" },
    embedded = { fill = "inset", color = "embedded", edge = false, opacity = "windowOpacity" },
    button = { fill = "panel", color = "raised", edge = false, opacity = "windowOpacity" },
    hud = { fill = "panel", color = "surface", edge = false, opacity = "hudOpacity" },
    chat = { fill = "panel", color = "surface", edge = false, opacity = "chatOpacity" },
    chatActive = { fill = "flat", color = "raised", edge = false, opacity = "chatActiveOpacity" },
}
Theme.surfaceRoles = SURFACES

-- Text roles: size plus semantic colour. Callers keep owning alignment,
-- wrapping and width, so a role never forces a layout.
local TEXT_ROLES = {
    title = { size = 20, color = "text" },
    body = { size = 14, color = "text" },
    label = { size = 13, color = "text" },
    value = { size = 13, color = "text" },
    muted = { size = 12, color = "muted" },
}
Theme.textRoles = TEXT_ROLES

-- Spacing comes from one short scale instead of per-module magic numbers.
Theme.spacing = { xs = 4, sm = 8, md = 12, lg = 20, xl = 28 }
Theme.edge = { thin = 1, normal = 2 }
Theme.focus = { width = 1 }
-- Reserved: a soft outer shadow needs a nine-slice edge that has not been
-- validated in game yet, so this build paints no shadow. The token exists so
-- the settings sample can adopt a measured value instead of guessing one.
Theme.shadow = { edge = 10, alpha = 0.35 }

function Theme:Accent()
    return self.colors[app.Store:Profile().appearance.accent]
end

function Theme:QualityColor(quality)
    quality = app.Capabilities.Plain(quality, "number")
    if not quality then return nil end
    if C_Item and type(C_Item.GetItemQualityColor) == "function" then
        local red, green, blue = C_Item.GetItemQualityColor(quality)
        if red then return red, green, blue end
    end
    local color = ITEM_QUALITY_COLORS and ITEM_QUALITY_COLORS[quality]
    if color then return color.r, color.g, color.b end
end

-- The game's own quest level colors: gray for trivial/low quests, green, yellow,
-- orange and red for harder ones. -> red, green, blue or nil.
function Theme:QuestColor(level)
    level = app.Capabilities.Plain(level, "number")
    if not level or type(GetQuestDifficultyColor) ~= "function" then return nil end
    local ok, color = pcall(GetQuestDifficultyColor, level)
    if not ok or type(color) ~= "table" then return nil end
    local red = app.Capabilities.Plain(color.r, "number")
    local green = app.Capabilities.Plain(color.g, "number")
    local blue = app.Capabilities.Plain(color.b, "number")
    if red and green and blue then return red, green, blue end
end

-- A vertical gradient wash inside a frame, from a lighter top to the panel
-- colour. A flat fill is what made every LumaUI panel read as "a grey box";
-- the wash gives a light source without adding a texture file. White first:
-- a plain colour set after a gradient clears it.
function Theme:Wash(frame, top, bottom)
    local wash = frame.lumaWash
    if not wash then
        wash = frame:CreateTexture(nil, "BACKGROUND", nil, -7)
        wash:SetPoint("TOPLEFT", 1, -1)
        wash:SetPoint("BOTTOMRIGHT", -1, 1)
        frame.lumaWash = wash
    end
    wash:SetColorTexture(1, 1, 1, 1)
    if type(wash.SetGradient) == "function" and type(_G.CreateColor) == "function" then
        local ok = pcall(wash.SetGradient, wash, "VERTICAL",
            CreateColor(top[1], top[2], top[3], 0.9),
            CreateColor(bottom[1], bottom[2], bottom[3], 0.35))
        if ok then return wash end
    end
    wash:Hide()
    return nil
end

function Theme:Panel(frame, raised)
    -- The panel texture already carries a vertical gradient and a soft edge
    -- falloff, so the backdrop only has to tint it: a plain white fill is what
    -- used to make every panel read as a grey box.
    frame:SetBackdrop({ bgFile = self.media.panel, edgeFile = self.white, edgeSize = 1,
        insets = { left = 1, right = 1, top = 1, bottom = 1 } })
    local bg, edge = self.colors[raised and "raised" or "surface"], self.colors.line
    local opacity = app.Store:Profile().appearance.opacity
    -- The texture is dark grey (0.68..1.0); lifting the tint keeps the panel
    -- from going muddy while still letting the gradient show.
    frame:SetBackdropColor(bg[1] * 2.1, bg[2] * 2.1, bg[3] * 2.1, opacity)
    frame:SetBackdropBorderColor(edge[1], edge[2], edge[3], 1)
    -- Keep the runtime wash off: the texture does this job now.
    if frame.lumaWash then frame.lumaWash:Hide() end
end

-- Background only; used where a separate accent frame already draws the edge,
-- so the two borders do not stack into a nested double outline.
function Theme:Surface(frame, raised)
    frame:SetBackdrop({ bgFile = self.white })
    local bg = self.colors[raised and "raised" or "surface"]
    frame:SetBackdropColor(bg[1], bg[2], bg[3], app.Store:Profile().appearance.opacity)
end

-- Opacity for a role token. A saved profile that predates the token falls back
-- to the legacy opacity, so an old database can never paint a surface fully
-- transparent.
function Theme:Opacity(token)
    local appearance = app.Store:Profile().appearance
    local value = token and appearance[token]
    value = app.Capabilities.Plain(value, "number")
    if value == nil then return appearance.opacity end
    return value
end

-- The one place that turns a semantic role into a backdrop. Edge thickness is
-- snapped to physical pixels, so a hairline stays one pixel on every UI scale.
function Theme:PaintSurface(frame, roleName)
    if not frame or type(frame.SetBackdrop) ~= "function" then return frame end
    local resolved = SURFACES[roleName] and roleName or "window"
    local role = SURFACES[resolved]
    -- A hairline is one physical pixel, whatever the UI scale: 1 at 100%, 2/3 at
    -- 150%, 0.5 at 200%.
    local edgeSize = app.Pixel:Pixels(self.edge.thin)
    -- "flat" is the plain white texture; every other role names a generated
    -- texture by purpose (panel gradient or inset wash).
    local fill = role.fill == "flat" and self.white or self.media[role.fill] or self.white
    local backdrop = { bgFile = fill }
    if role.edge then
        backdrop.edgeFile = self.white
        backdrop.edgeSize = edgeSize
        backdrop.insets = { left = edgeSize, right = edgeSize, top = edgeSize, bottom = edgeSize }
    end
    frame:SetBackdrop(backdrop)
    local color = self.colors[role.color]
    -- The generated textures are dark grey gradients; lifting the tint keeps
    -- them from going muddy, exactly like the legacy Panel role does.
    local boost = role.fill == "flat" and 1 or 2.1
    frame:SetBackdropColor(color[1] * boost, color[2] * boost, color[3] * boost, self:Opacity(role.opacity))
    if role.edge then
        local line = self.colors.line
        frame:SetBackdropBorderColor(line[1], line[2], line[3], 1)
    end
    frame.lumaSurfaceRole = resolved
    -- The runtime wash belongs to the legacy Panel role only.
    if frame.lumaWash then frame.lumaWash:Hide() end
    return frame
end

function Theme:TextRole(parent, roleName)
    local role = TEXT_ROLES[roleName] or TEXT_ROLES.body
    local text = self:Text(parent, role.size, role.color == "muted")
    text.lumaTextRole = roleName or "body"
    return text
end

function Theme:Space(name)
    return self.spacing[name] or self.spacing.md
end

-- Focus uses the live accent so the ring and the selected state always agree.
function Theme:FocusColor()
    return self:Accent()
end

function Theme:Text(parent, size, muted)
    local text = parent:CreateFontString(nil, "OVERLAY")
    local font = GameFontNormal:GetFont()
    text:SetFont(font, size or 13, "")
    local color = self.colors[muted and "muted" or "text"]
    text:SetTextColor(color[1], color[2], color[3])
    text:SetJustifyH("LEFT")
    return text
end

function Theme:Rule(parent)
    local rule = parent:CreateTexture(nil, "ARTWORK")
    local c = self:Accent()
    rule:SetColorTexture(c[1], c[2], c[3], 1)
    return rule
end

function Theme:Bar(parent, height)
    local bar = CreateFrame("StatusBar", nil, parent)
    bar:SetHeight(height)
    bar:SetStatusBarTexture(self.media.bar)
    local c = self:Accent()
    bar:SetStatusBarColor(c[1], c[2], c[3])
    local background = bar:CreateTexture(nil, "BACKGROUND")
    background:SetAllPoints()
    local b = self.colors.raised
    background:SetColorTexture(b[1], b[2], b[3], 1)
    bar.background = background
    return bar
end

-- Two-tone bar fills: the recipe (not the palette) of a modern gradient bar —
-- one base color derives a dark end, a light end and a dimmed middle for the
-- empty part; the fill texture is painted white and carries the color ramp.
-- Colors come from the game itself (class colors, reactions, power types) or
-- LumaUI's own palette. Clients without Texture:SetGradient fall back to the
-- flat middle, so the fill stays readable everywhere.
local PAIR_DARK, PAIR_LIGHT, BACK_DIM = 0.45, 0.25, 0.4

function Theme:Pair(base)
    if type(base) ~= "table" then return nil, nil end
    local lo = { base[1] * PAIR_DARK, base[2] * PAIR_DARK, base[3] * PAIR_DARK }
    local hi = { base[1] + (1 - base[1]) * PAIR_LIGHT, base[2] + (1 - base[2]) * PAIR_LIGHT,
        base[3] + (1 - base[3]) * PAIR_LIGHT }
    return lo, hi
end

function Theme:PaintBar(bar, base)
    if not bar or type(base) ~= "table" then return end
    local lo, hi = self:Pair(base)
    if not lo then return end
    local mid = { (lo[1] + hi[1]) / 2, (lo[2] + hi[2]) / 2, (lo[3] + hi[3]) / 2 }
    local back = bar.background
    if back and type(back.SetColorTexture) == "function" then
        back:SetColorTexture(mid[1] * BACK_DIM, mid[2] * BACK_DIM, mid[3] * BACK_DIM, 1)
    end
    local ok, fill = pcall(bar.GetStatusBarTexture, bar)
    if ok and fill and type(fill.SetGradient) == "function" and type(_G.CreateColor) == "function" then
        -- White first: a plain color set after the gradient would clear it.
        bar:SetStatusBarColor(1, 1, 1, 1)
        pcall(fill.SetGradient, fill, "HORIZONTAL",
            CreateColor(lo[1], lo[2], lo[3], 1), CreateColor(hi[1], hi[2], hi[3], 1))
        bar.gradient = { lo = lo, hi = hi }
    else
        bar.gradient = nil
        bar:SetStatusBarColor(mid[1], mid[2], mid[3], 1)
    end
end

-- A unit's base color: its class color for players, else how it reacts to the
-- player (tapped, hostile, neutral, friendly). Everything secret or unknown
-- falls back to the accent, never to a guess.
function Theme:UnitColor(unit)
    local Plain = app.Capabilities.Plain
    local accent = self:Accent()
    local fallback = { accent[1], accent[2], accent[3] }
    if type(UnitIsPlayer) == "function" then
        local ok, isPlayer = pcall(UnitIsPlayer, unit)
        if ok and Plain(isPlayer, "boolean") == true then
            local okc, _, token = pcall(UnitClass, unit)
            token = okc and Plain(token, "string") or nil
            local palette = _G.RAID_CLASS_COLORS
            local color = token and type(palette) == "table" and palette[token]
            local r = color and Plain(color.r, "number")
            local g = color and Plain(color.g, "number")
            local b = color and Plain(color.b, "number")
            if r and g and b then return { r, g, b } end
            return fallback
        end
    end
    if type(UnitIsTapDenied) == "function" then
        local ok, tapped = pcall(UnitIsTapDenied, unit)
        if ok and Plain(tapped, "boolean") == true then return self.colors.tapped end
    end
    if type(UnitReaction) == "function" then
        local ok, reaction = pcall(UnitReaction, unit, "player")
        reaction = ok and Plain(reaction, "number") or nil
        if reaction then
            if reaction <= 3 then return self.colors.hostile end
            if reaction == 4 then return self.colors.neutral end
            return self.colors.friendly
        end
    end
    return fallback
end

-- A power type's base color from the game's own palette, with fixed fallbacks
-- for the common types and the old preview blue for anything unknown.
function Theme:PowerColor(unit)
    local fallback = { 0.40, 0.58, 0.84 }
    if type(UnitPowerType) ~= "function" then return fallback end
    local Plain = app.Capabilities.Plain
    local ok, kind, token = pcall(UnitPowerType, unit)
    if not ok then return fallback end
    kind = Plain(kind, "number")
    token = Plain(token, "string")
    local names = { [0] = "MANA", [1] = "RAGE", [2] = "FOCUS", [3] = "ENERGY" }
    local key = token or (kind and names[kind]) or "MANA"
    local palette = _G.PowerBarColor
    local color = type(palette) == "table" and palette[key]
    local r = color and Plain(color.r, "number")
    local g = color and Plain(color.g, "number")
    local b = color and Plain(color.b, "number")
    if r and g and b then return { r, g, b } end
    local defaults = { MANA = { 0.10, 0.50, 0.90 }, RAGE = { 0.85, 0.20, 0.18 },
        FOCUS = { 0.90, 0.55, 0.25 }, ENERGY = { 0.95, 0.85, 0.25 } }
    return defaults[key] or fallback
end
