    return self:Accent()
end

function Theme:Text(parent, size, muted)
    local text = parent:CreateFontString(nil, "OVERLAY")
    -- One resolved face for every string: GameFontNormal's face is only the
    -- last-resort fallback inside Type:Face().
    local font = app.Type and app.Type:Face() or GameFontNormal:GetFont()
    text:SetFont(font, size or 13, "")
    local color = self.colors[muted and "muted" or "text"]
    text:SetTextColor(color[1], color[2], color[3])
    text:SetJustifyH("LEFT")
    return text
end

function Theme:Rule(parent)
    local rule = parent:CreateTexture(nil, "ARTWORK")
    local c = self:Accent()
    rule:SetColorTexture(c[1], c[2], c[3], 1)
    return rule
end

function Theme:Bar(parent, height)
    local bar = CreateFrame("StatusBar", nil, parent)
    bar:SetHeight(height)
    bar:SetStatusBarTexture(self.media.bar)
    local c = self:Accent()
    bar:SetStatusBarColor(c[1], c[2], c[3])
    local background = bar:CreateTexture(nil, "BACKGROUND")
    background:SetAllPoints()
    local b = self.colors.raised
    background:SetColorTexture(b[1], b[2], b[3], 1)
    bar.background = background
    return bar
end

-- Two-tone bar fills: the recipe (not the palette) of a modern gradient bar —
-- one base color derives a dark end, a light end and a dimmed middle for the
-- empty part; the fill texture is painted white and carries the color ramp.
-- Colors come from the game itself (class colors, reactions, power types) or
-- LumaUI's own palette. Clients without Texture:SetGradient fall back to the
-- flat middle, so the fill stays readable everywhere.
local PAIR_DARK, PAIR_LIGHT, BACK_DIM = 0.45, 0.25, 0.4

function Theme:Pair(base)
    if type(base) ~= "table" then return nil, nil end
    local lo = { base[1] * PAIR_DARK, base[2] * PAIR_DARK, base[3] * PAIR_DARK }
    local hi = { base[1] + (1 - base[1]) * PAIR_LIGHT, base[2] + (1 - base[2]) * PAIR_LIGHT,
        base[3] + (1 - base[3]) * PAIR_LIGHT }
    return lo, hi
end

function Theme:PaintBar(bar, base)
    if not bar or type(base) ~= "table" then return end
    local lo, hi = self:Pair(base)
    if not lo then return end
    local mid = { (lo[1] + hi[1]) / 2, (lo[2] + hi[2]) / 2, (lo[3] + hi[3]) / 2 }
    local back = bar.background
    if back and type(back.SetColorTexture) == "function" then
        back:SetColorTexture(mid[1] * BACK_DIM, mid[2] * BACK_DIM, mid[3] * BACK_DIM, 1)
    end
    local ok, fill = pcall(bar.GetStatusBarTexture, bar)
    if ok and fill and type(fill.SetGradient) == "function" and type(_G.CreateColor) == "function" then
        -- White first: a plain color set after the gradient would clear it.
        bar:SetStatusBarColor(1, 1, 1, 1)
        pcall(fill.SetGradient, fill, "HORIZONTAL",
            CreateColor(lo[1], lo[2], lo[3], 1), CreateColor(hi[1], hi[2], hi[3], 1))
        bar.gradient = { lo = lo, hi = hi }
    else
        bar.gradient = nil
        bar:SetStatusBarColor(mid[1], mid[2], mid[3], 1)
    end
end

-- The Pearl combat fill: one fixed colour on the matte texture, an 8% vertical
-- light drop and a dimmed track. No horizontal gradient — a short enemy or
-- resource bar keeps its saturation instead of fading at one end. This is a
-- separate role from PaintBar on purpose: panels and long progress bars keep
-- the gradient recipe that already passed validation.
function Theme:PaintCombatBar(bar, base)
    if not bar or type(base) ~= "table" then return end
    local back = bar.background
    if back and type(back.SetColorTexture) == "function" then
        back:SetColorTexture(base[1] * 0.22, base[2] * 0.22, base[3] * 0.22, 1)
    end
    if type(bar.SetStatusBarTexture) == "function" then
        pcall(bar.SetStatusBarTexture, bar, self.media.combatFill)
    end
    bar.gradient = nil
    bar:SetStatusBarColor(base[1], base[2], base[3], 1)
end

-- 013 Pearl health role: the matte fill carries the unit colour, the empty rail
-- stays one near-neutral cool grey whatever the unit is, so a half-empty bar
-- reads as "fill on a rail" instead of one big same-hue gradient. The rail and
-- the fill share one hairline edge owned by the caller. Only plain colours are
-- accepted; the base comes from public identity APIs, never from health.
Theme.matte = {
    rail = { 0.075, 0.085, 0.10, 0.94 },
    absorb = { 0.88, 0.94, 1.00, 0.34 },
    deadFill = { 0.42, 0.42, 0.44 },
}

function Theme:PaintMatteBar(bar, base)
    if not bar or type(base) ~= "table" then return end
    local back = bar.background
    if back and type(back.SetColorTexture) == "function" then
        local rail = self.matte.rail
        back:SetColorTexture(rail[1], rail[2], rail[3], rail[4])
    end
    if type(bar.SetStatusBarTexture) == "function" then
        pcall(bar.SetStatusBarTexture, bar, self.media.combatFill)
    end
    bar.gradient = nil
    bar:SetStatusBarColor(base[1], base[2], base[3], 1)
end

-- A small scrim under short text drawn over the world: one texture per host,
-- created lazily, tinted by the texture itself (dark and edge-faded). Returns
-- the texture so the caller can size or hide it; a host that cannot parent
-- textures leaves nil and nothing is drawn.
function Theme:Scrim(host, padding)
    if not host or type(host.CreateTexture) ~= "function" then return nil end
    local texture = host.lumaScrim
    if not texture then
        texture = host:CreateTexture(nil, "BACKGROUND", nil, -6)
        host.lumaScrim = texture
    end
    local pad = padding or 4
    texture:ClearAllPoints()
    texture:SetPoint("TOPLEFT", host, "TOPLEFT", -pad, pad)
    texture:SetPoint("BOTTOMRIGHT", host, "BOTTOMRIGHT", pad, -pad)
    if type(texture.SetTexture) == "function" then
        local ok = pcall(texture.SetTexture, texture, self.media.scrim)
        if not ok and type(texture.SetColorTexture) == "function" then
            texture:SetColorTexture(0.05, 0.07, 0.09, 0.5)
        end
    end
    if type(texture.SetVertexColor) == "function" then texture:SetVertexColor(1, 1, 1, 1) end
    texture:Show()
    return texture
end

-- A unit's base color: its class color for players, else how it reacts to the
-- player (tapped, hostile, neutral, friendly). Everything secret or unknown
-- falls back to the accent, never to a guess.
function Theme:UnitColor(unit)
    local Plain = app.Capabilities.Plain
    local accent = self:Accent()
    local fallback = { accent[1], accent[2], accent[3] }
    if type(UnitIsPlayer) == "function" then
        local ok, isPlayer = pcall(UnitIsPlayer, unit)
        if ok and Plain(isPlayer, "boolean") == true then
            local okc, _, token = pcall(UnitClass, unit)
            token = okc and Plain(token, "string") or nil
            local palette = _G.RAID_CLASS_COLORS
            local color = token and type(palette) == "table" and palette[token]
            local r = color and Plain(color.r, "number")
            local g = color and Plain(color.g, "number")
            local b = color and Plain(color.b, "number")
            if r and g and b then return { r, g, b } end
            return fallback
        end
    end
    if type(UnitIsTapDenied) == "function" then
        local ok, tapped = pcall(UnitIsTapDenied, unit)
        if ok and Plain(tapped, "boolean") == true then return self.colors.tapped end
    end
    if type(UnitReaction) == "function" then
        local ok, reaction = pcall(UnitReaction, unit, "player")
        reaction = ok and Plain(reaction, "number") or nil
        if reaction then
            if reaction <= 3 then return self.colors.hostile end
            if reaction == 4 then return self.colors.neutral end
            return self.colors.friendly
        end
    end
    return fallback
end

-- A power type's base color from the game's own palette, with fixed fallbacks
-- for the common types and the old preview blue for anything unknown.
function Theme:PowerColor(unit)
    local fallback = { 0.40, 0.58, 0.84 }
    if type(UnitPowerType) ~= "function" then return fallback end
    local Plain = app.Capabilities.Plain
    local ok, kind, token = pcall(UnitPowerType, unit)
    if not ok then return fallback end
    kind = Plain(kind, "number")
    token = Plain(token, "string")
    local names = { [0] = "MANA", [1] = "RAGE", [2] = "FOCUS", [3] = "ENERGY" }
    local key = token or (kind and names[kind]) or "MANA"
    local palette = _G.PowerBarColor
    local color = type(palette) == "table" and palette[key]
    local r = color and Plain(color.r, "number")
    local g = color and Plain(color.g, "number")
    local b = color and Plain(color.b, "number")
    if r and g and b then return { r, g, b } end
    local defaults = { MANA = { 0.10, 0.50, 0.90 }, RAGE = { 0.85, 0.20, 0.18 },
        FOCUS = { 0.90, 0.55, 0.25 }, ENERGY = { 0.95, 0.85, 0.25 } }
    return defaults[key] or fallback
end
