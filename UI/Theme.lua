function Theme:Accent()
    return self.colors[app.Store:Profile().appearance.accent]
end

-- Class token to colour, read from the client's own class colour table. Only a
-- plain token is looked up: a missing table or token returns nil so the caller
-- keeps its previous colour instead of inventing one.
function Theme:ClassColor(token)
    token = app.Capabilities.Plain(token, "string")
    if not token then return nil end
    local colors = _G.CUSTOM_CLASS_COLORS or _G.RAID_CLASS_COLORS
    local color = colors and colors[token]
    if not color then return nil end
    local red, green, blue = color.r, color.g, color.b
    red, green, blue = app.Capabilities.Plain(red, "number"),
        app.Capabilities.Plain(green, "number"), app.Capabilities.Plain(blue, "number")
    if not red or not green or not blue then return nil end
    return red, green, blue
end

function Theme:QualityColor(quality)
    quality = app.Capabilities.Plain(quality, "number")
    if not quality then return nil end
    if C_Item and type(C_Item.GetItemQualityColor) == "function" then
        local red, green, blue = C_Item.GetItemQualityColor(quality)
        if red then return red, green, blue end
    end
    local color = ITEM_QUALITY_COLORS and ITEM_QUALITY_COLORS[quality]
    if color then return color.r, color.g, color.b end
end

-- The game's own quest level colors: gray for trivial/low quests, green, yellow,
-- orange and red for harder ones. -> red, green, blue or nil.
function Theme:QuestColor(level)
    level = app.Capabilities.Plain(level, "number")
    if not level or type(GetQuestDifficultyColor) ~= "function" then return nil end
    local ok, color = pcall(GetQuestDifficultyColor, level)
    if not ok or type(color) ~= "table" then return nil end
    local red = app.Capabilities.Plain(color.r, "number")
    local green = app.Capabilities.Plain(color.g, "number")
    local blue = app.Capabilities.Plain(color.b, "number")
    if red and green and blue then return red, green, blue end
end

-- A vertical gradient wash inside a frame, from a lighter top to the panel
-- colour. A flat fill is what made every LumaUI panel read as "a grey box";
-- the wash gives a light source without adding a texture file. White first:
-- a plain colour set after a gradient clears it.
function Theme:Wash(frame, top, bottom)
    local wash = frame.lumaWash
    if not wash then
        wash = frame:CreateTexture(nil, "BACKGROUND", nil, -7)
        wash:SetPoint("TOPLEFT", 1, -1)
        wash:SetPoint("BOTTOMRIGHT", -1, 1)
        frame.lumaWash = wash
    end
    wash:SetColorTexture(1, 1, 1, 1)
    if type(wash.SetGradient) == "function" and type(_G.CreateColor) == "function" then
        local ok = pcall(wash.SetGradient, wash, "VERTICAL",
            CreateColor(top[1], top[2], top[3], 0.9),
            CreateColor(bottom[1], bottom[2], bottom[3], 0.35))
        if ok then return wash end
    end
    wash:Hide()
    return nil
end

function Theme:Panel(frame, raised)
    -- The panel texture already carries a vertical gradient and a soft edge
    -- falloff, so the backdrop only has to tint it: a plain white fill is what
    -- used to make every panel read as a grey box.
    frame:SetBackdrop({ bgFile = self.media.panel, edgeFile = self.white, edgeSize = 1,
        insets = { left = 1, right = 1, top = 1, bottom = 1 } })
    local bg, edge = self.colors[raised and "raised" or "surface"], self.colors.line
    local opacity = app.Store:Profile().appearance.opacity
    -- The texture is dark grey (0.68..1.0); lifting the tint keeps the panel
    -- from going muddy while still letting the gradient show.
    frame:SetBackdropColor(bg[1] * 2.1, bg[2] * 2.1, bg[3] * 2.1, opacity)
    frame:SetBackdropBorderColor(edge[1], edge[2], edge[3], 1)
    -- Keep the runtime wash off: the texture does this job now.
    if frame.lumaWash then frame.lumaWash:Hide() end
end

-- Background only; used where a separate accent frame already draws the edge,
-- so the two borders do not stack into a nested double outline.
function Theme:Surface(frame, raised)
    frame:SetBackdrop({ bgFile = self.white })
    local bg = self.colors[raised and "raised" or "surface"]
    frame:SetBackdropColor(bg[1], bg[2], bg[3], app.Store:Profile().appearance.opacity)
end

-- Opacity for a role token. A saved profile that predates the token falls back
-- to the legacy opacity, so an old database can never paint a surface fully
-- transparent.
function Theme:Opacity(token)
    local appearance = app.Store:Profile().appearance
    local value = token and appearance[token]
    value = app.Capabilities.Plain(value, "number")
    if value == nil then return appearance.opacity end
    return value
end

-- The one place that turns a semantic role into a backdrop. Edge thickness is
-- snapped to physical pixels, so a hairline stays one pixel on every UI scale.
function Theme:PaintSurface(frame, roleName)
    if not frame or type(frame.SetBackdrop) ~= "function" then return frame end
    local resolved = SURFACES[roleName] and roleName or "window"
    local role = SURFACES[resolved]
    -- A hairline is one physical pixel, whatever the UI scale: 1 at 100%, 2/3 at
    -- 150%, 0.5 at 200%.
    local edgeSize = app.Pixel:Pixels(self.edge.thin)
    -- "flat" is the plain white texture; every other role names a generated
    -- texture by purpose (panel gradient or inset wash).
    local fill = role.fill == "flat" and self.white or self.media[role.fill] or self.white
    local backdrop = { bgFile = fill }
    if role.edge then
        backdrop.edgeFile = self.white
        backdrop.edgeSize = edgeSize
        backdrop.insets = { left = edgeSize, right = edgeSize, top = edgeSize, bottom = edgeSize }
    end
    frame:SetBackdrop(backdrop)
    local color = self.colors[role.color]
    -- The generated textures are dark grey gradients; lifting the tint keeps
    -- them from going muddy, exactly like the legacy Panel role does.
    local boost = role.fill == "flat" and 1 or 2.1
    frame:SetBackdropColor(color[1] * boost, color[2] * boost, color[3] * boost, self:Opacity(role.opacity))
    if role.edge then
        local line = self.colors.line
        frame:SetBackdropBorderColor(line[1], line[2], line[3], 1)
    end
    frame.lumaSurfaceRole = resolved
    -- The runtime wash belongs to the legacy Panel role only.
    if frame.lumaWash then frame.lumaWash:Hide() end
    return frame
end

function Theme:TextRole(parent, roleName)
    local role = TEXT_ROLES[roleName] or TEXT_ROLES.body
    local text = self:Text(parent, role.size, role.color == "muted")
    text.lumaTextRole = roleName or "body"
    return text
end

